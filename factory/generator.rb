# frozen_string_literal: true

require_relative 'catalog'

# Reusable generation module. Parses one of the short tzdata-style rule
# sources and emits TZInfo format-1 Ruby module source. Every emitted module
# uses only the work-order-approved rewrite forms:
#
#   * full data zone (all declared offsets and transitions)
#   * windowed data zone (the offset active at the window start is retained as
#     the initial offset so reads that fold back from just outside the UTC edge
#     still resolve; only transitions inside the window are kept)
#   * linked zone (an alias to a canonical identifier)
module Generator
  ParsedZone = Struct.new(:identifier, :offsets, :transitions, keyword_init: true)
  ParsedSource = Struct.new(:edition, :zones, :links, keyword_init: true)

  HEADER = <<~HEADER.freeze
    # encoding: UTF-8

    # This file contains data derived from a work-order tzdata-style rule
    # source and was generated by factory/generator.rb.
  HEADER

  # Escape an identifier path component exactly as RubyDataSource expects on
  # disk and as a constant name ('-' => '__m__', '+' => '__p__').
  def self.escape(part)
    part.gsub('-', '__m__').gsub('+', '__p__')
  end

  def self.parse(edition, path)
    zones = {}
    links = {}
    current = nil

    File.readlines(path, chomp: true).each do |raw|
      line = raw.sub(/#.*\z/, '').strip
      next if line.empty?
      keyword, *args = line.split(/\s+/)

      case keyword
      when 'ZONE'
        current = args.fetch(0)
        zones[current] = ParsedZone.new(identifier: current, offsets: [], transitions: [])
      when 'OFFSET'
        sym, base, std, abbr = args
        zones.fetch(current).offsets << [sym.to_sym, base.to_i, std.to_i, abbr]
      when 'TRANS'
        year, month, sym, epoch = args
        zones.fetch(current).transitions << [year.to_i, month.to_i, sym.to_sym, epoch.to_i]
      when 'LINK'
        identifier, target = args
        links[identifier] = target
        current = nil
      else
        raise "unknown rule keyword #{keyword} in #{path}"
      end
    end

    ParsedSource.new(edition: edition, zones: zones, links: links)
  end

  # Build a module file from an array of "body" lines (already indented to sit
  # inside the innermost identifier module). Nesting depth is derived from the
  # identifier, so America/Indiana/Indianapolis nests as deeply as required.
  def self.render(identifier, body_lines)
    parts = identifier.split('/').map { |p| escape(p) }
    lines = HEADER.lines(chomp: true) + ['']
    lines << 'module TZInfo'
    lines << '  module Data'
    lines << '    module Definitions'
    parts.each_with_index { |mod, i| lines << "#{'  ' * (3 + i)}module #{mod}" }
    inner = 3 + parts.size
    body_lines.each { |text| lines << "#{'  ' * inner}#{text}" }
    parts.size.times { |i| lines << "#{'  ' * (inner - 1 - i)}end" }
    lines << '    end' # Definitions
    lines << '  end'   # Data
    lines << 'end'     # TZInfo
    lines.join("\n") + "\n"
  end

  def self.emit_data_module(identifier, offsets, transitions)
    body = ['include TimezoneDefinition', '', "timezone '#{identifier}' do |tz|"]
    offsets.each do |sym, base, std, abbr|
      body << "  tz.offset :#{sym}, #{base}, #{std}, #{symbol_literal(abbr)}"
    end
    unless transitions.empty?
      body << ''
      transitions.each do |year, month, sym, epoch|
        body << "  tz.transition #{year}, #{month}, :#{sym}, #{epoch}"
      end
    end
    body << 'end'
    render(identifier, body)
  end

  # Emit a valid Ruby symbol literal, quoting abbreviations such as '+06' that
  # are not valid bare symbols (the shipped gem writes these as :'+06').
  def self.symbol_literal(name)
    name.match?(/\A[A-Za-z_]\w*\z/) ? ":#{name}" : ":'#{name}'"
  end

  def self.emit_link_module(identifier, target)
    body = [
      'include TimezoneDefinition',
      '',
      "linked_timezone '#{identifier}', '#{target}'"
    ]
    render(identifier, body)
  end

  # Offset symbol active at a given UTC epoch (the last transition at or before
  # it; falls back to the first declared offset).
  def self.offset_active_at(zone, epoch)
    active = zone.offsets.first&.first
    zone.transitions.each do |_y, _m, sym, tr_epoch|
      break if tr_epoch > epoch
      active = sym
    end
    active
  end

  # Emit a module clipped to a local window. The initial offset is the one in
  # effect at window start, so a local time near either edge whose UTC instant
  # folds just outside the window is still answered correctly (nothing is lost
  # by truncating at the UTC edge or by two neighbouring offsets being equal).
  def self.emit_window_module(identifier, zone, start_epoch, end_epoch)
    initial = offset_active_at(zone, start_epoch)
    kept_trans = zone.transitions.select { |_y, _m, _s, e| e >= start_epoch && e <= end_epoch }
    used_syms = [initial] + kept_trans.map { |_y, _m, s, _e| s }
    kept_offsets = zone.offsets.select { |sym, *_| used_syms.include?(sym) }
    kept_offsets.sort_by! { |sym, *_| sym == initial ? 0 : 1 }
    emit_data_module(identifier, kept_offsets, kept_trans)
  end

  # Relative on-disk path of a definition module.
  def self.definition_path(identifier)
    File.join('definitions', *identifier.split('/').map { |p| escape(p) }) + '.rb'
  end

  # Produce the module source for a candidate against a parsed rule source.
  # `window` is a [start_epoch, end_epoch] pair or nil for a full module.
  def self.source_for(candidate, parsed, window: nil)
    case candidate.form
    when :link
      emit_link_module(candidate.identifier, candidate.target)
    when :full_rule
      zone = parsed.zones.fetch(candidate.identifier)
      emit_data_module(candidate.identifier, zone.offsets, zone.transitions)
    when :window_rule
      zone = parsed.zones.fetch(candidate.identifier)
      raise "window_rule candidate #{candidate.code} needs a window" unless window
      emit_window_module(candidate.identifier, zone, window[0], window[1])
    else
      raise "unknown form #{candidate.form}"
    end
  end
end
